import shutil

import pytest
from conftest import FIXTURES

DOCS = FIXTURES / "docs"
LINK_LINE = "read @CHARTER.md before creating or editing any note here"

BOOK = """\
charter: 1
root: docs
{top}kinds:
  book:
    path: "Books/{{title}}.md"
    fields:
      kind: {{type: string, required: true}}
      title: {{type: string, required: true, matches_filename: true}}
"""
AGENTS = "agents:\n  file: AGENTS.md\n"
NOTE = "---\nkind: book\ntitle: Dune\n---\n"


@pytest.fixture
def docs_kb(tmp_path):
    """A writable copy of the docs fixture."""
    kb = tmp_path / "kb"
    shutil.copytree(DOCS, kb, ignore=shutil.ignore_patterns("*.golden.md"))
    return kb


@pytest.fixture
def kb(make_kb):
    def make(top="", files=None):
        files = {"charter.yaml": BOOK.format(top=top), "docs/Books/Dune.md": NOTE, **(files or {})}
        return make_kb(files, agents_include=True)

    return make


def _codes(result):
    return [(d["path"], d["code"]) for d in result.json()["diagnostics"]]


