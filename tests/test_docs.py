def test_link_agents_on_a_folder_reports_it_and_leaves_the_folder(charter, docs_kb):
    (docs_kb / "AGENTS.md").mkdir()
    (docs_kb / "CHARTER.md").unlink(missing_ok=True)

    result = charter("docs", "--link-agents", cwd=docs_kb)

