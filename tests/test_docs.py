def test_link_agents_check_with_a_file_fails_only_while_the_rulebook_is_stale(charter, docs_kb):
    charter("docs", "--link-agents", cwd=docs_kb)
    current = charter("docs", "--check", "--link-agents", cwd=docs_kb)
    assert current.exit_code == 0
    assert "agents-include/" not in current.stdout

    # Same command, same AGENTS.md: staleness alone flips it, and with another code than the folder case.
    rulebook = docs_kb / "CHARTER.md"
    rulebook.write_text(rulebook.read_text(encoding="utf-8") + "edited\n", encoding="utf-8")
    stale = charter("docs", "--check", "--link-agents", cwd=docs_kb)
    assert stale.exit_code == 1
    assert "agents-include/stale" in stale.stdout
    assert "agents-include/missing-file" not in stale.stdout


