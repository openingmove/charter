def test_the_rulebook_is_the_whole_description_under_a_generated_header(charter, docs_kb):
    charter("docs", cwd=docs_kb)
    described = charter("describe", cwd=docs_kb).stdout

    rulebook = (docs_kb / "CHARTER.md").read_text(encoding="utf-8")
    assert rulebook.startswith("<!-- Generated by `charter docs` from charter.yaml: do not edit.")
    assert rulebook.endswith(described)
    assert "Never add a `Charter-Allow:` trailer" in rulebook
    assert "| `agents-include` |" in rulebook


def test_the_workflow_is_identical_in_a_docs_only_and_an_agents_rulebook(charter, tmp_path):
    def rulebook_of(name, top):
        base = tmp_path / name
        (base / "docs" / "Books").mkdir(parents=True)
        (base / "charter.yaml").write_text(BOOK.format(top=top), encoding="utf-8")
        (base / "docs" / "Books" / "Dune.md").write_text(NOTE, encoding="utf-8")
        charter("docs", cwd=base)
        return (base / "CHARTER.md").read_text(encoding="utf-8")

    docs_only = rulebook_of("docs-only", "docs:\n  output: CHARTER.md\n")
    with_agents = rulebook_of("with-agents", AGENTS)

    # Guards against the two contracts silently becoming the same mode.
    assert "agents:" not in (tmp_path / "docs-only" / "charter.yaml").read_text(encoding="utf-8")
    assert "agents:" in (tmp_path / "with-agents" / "charter.yaml").read_text(encoding="utf-8")

    def workflow(rulebook):
        return rulebook[rulebook.index("## Working here") : rulebook.index("# Kinds")]

    assert workflow(docs_only) == workflow(with_agents)


