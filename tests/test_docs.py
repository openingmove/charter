@pytest.mark.parametrize(
    "top",
    [
        "agents:\n  file: ../AGENTS.md\n",
        "agents:\n  path: AGENTS.md\n",
        "agents:\n  file: ''\n",
    ],
)
def test_an_invalid_agents_key_is_a_contract_error(charter, kb, top):
    result = charter("validate", "--format", "json", cwd=kb(top=top))

    assert result.exit_code == 2
    assert _codes(result) == [("charter.yaml", "contract/invalid")]


@pytest.mark.parametrize(
    "top, line",
    [
        ("agents:\n  file: RULES.md\ndocs:\n  output: RULES.md\n", 2),
        ("agents:\n  file: docs/RULES.md\ndocs:\n  output: ./docs/RULES.md\n", 2),
        ("agents:\n  file: docs/RULES.md\ndocs:\n  output: docs//RULES.md\n", 2),
        ("agents:\n  file: docs\\RULES.md\ndocs:\n  output: docs/RULES.md\n", 2),
        ("agents:\n  file: docs/x/../RULES.md\ndocs:\n  output: docs/RULES.md\n", 2),
        # Both defaulted onto one file: only agents.file is named, so the clash is reported on it.
        ("agents:\n  file: CHARTER.md\n", 2),
        # Only docs.output is named: the default AGENTS.md is the clash.
        ("agents: {}\ndocs:\n  output: AGENTS.md\n", 3),
    ],
)
def test_agents_file_equal_to_docs_output_is_a_contract_error(charter, kb, top, line):
    base = kb(top=top)
    result = charter("validate", "--format", "json", cwd=base)

    assert result.exit_code == 2
    assert _codes(result) == [("charter.yaml", "contract/invalid")]
    diagnostic = result.json()["diagnostics"][0]
    assert "name the same file" in diagnostic["message"]
    # `line` counts within `top`; the report sits on that line of the written contract.
    written = (base / "charter.yaml").read_text(encoding="utf-8").splitlines()
    assert written[diagnostic["line"] - 1] == top.splitlines()[line - 1]


