"""The generated rulebook (`docs.output`)."""

from charter import description
from charter.checks.agents_include import STALE
from charter.contract import Contract
from charter.diagnostics import Diagnostic, Refused, Severity
from charter.files import writing
from charter.tree import decode

WRITE_FAILED = "docs/write-failed"
# What a stale rulebook is reported as without the agent layer, where no diagnostic may name agents.
DOCS_STALE = "docs/stale"
# What `charter docs` reports for a contract with nothing to generate.
NO_RULEBOOK = "usage/no-rulebook"


def staleness(contract: Contract) -> Diagnostic | None:
    """Why `docs.output` differs from the rulebook the contract generates; None when it is up to date."""
    output = contract.docs_output
    content = contract.tree.read([output]).get(output)
    if content is None and not contract.tree.exists(output):
        return _stale(contract, f"`{output}` does not exist.")
    try:
        # Universal newlines: a checkout with CRLF line endings is as fresh as the LF original.
        current = None if content is None else decode(content, "utf-8")
    except UnicodeDecodeError:
        current = None
    if current == rulebook(contract):
        return None
    return _stale(contract, f"`{output}` is out of date with the contract.")


def _stale(contract: Contract, message: str) -> Diagnostic:
    code = STALE if contract.agent_layer_on else DOCS_STALE
    return Diagnostic(contract.docs_output, None, Severity.ERROR, code, message, "Run `charter docs` to regenerate it.")


def rulebook(contract: Contract) -> str:
    """The rulebook's exact text: LF line endings and contract order, so every platform renders the same bytes."""
    return _HEADER.format(contract=contract.file) + description.to_markdown(description.build_description(contract))


_HEADER = """\
<!-- Generated by `charter docs` from {contract}: do not edit. Run `charter docs` after changing the contract. -->

# Rules of this knowledge base

`{contract}` declares the kinds of note this knowledge base holds, their fields and where they live. \
This file explains it; `charter validate` enforces it.

## Working here

Whoever edits a note here, a person or a tool, follows this workflow:

1. Read these rules before creating or editing any note.
2. Create a note with the `charter new` command given for each kind: it places, names and fills in the note. \
Run `charter describe KIND` for the rules of one kind.
3. After each edit, run `charter validate --file PATH` and fix what it reports before moving on.
4. Before changing a fact other notes may depend on, run `charter sweep` to find them.
5. Never change `{contract}` to make a note pass. If the contract itself seems wrong, stop and tell the human: \
only the human decides to change it, by running Evolve, the charter skill for the deliberate change of a contract.
6. Never add a `Charter-Allow:` trailer to a commit message unless the human explicitly asks for one: \
overriding an edit policy is their decision.
7. This contract wins over any other guidance about how a document should look or be organised.

"""


def write_rulebook(contract: Contract, failure_code: str = WRITE_FAILED) -> bool:
    """Writes `docs.output` unless it is up to date; True when written. Raises Refused."""
    if staleness(contract) is None:
        return False
    output = contract.base_dir / contract.docs_output
    with writing(contract.docs_output, failure_code):
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(rulebook(contract), encoding="utf-8", newline="\n")
    return True
